// v2 基础 Token（radius / text / space / density / elevation / motion / zIndex / breakpoint / brand）
// 的输出：--klc-* CSS 与带类型的 TS 对象。与 Theme 层（colors/spacing/typography/motion 旧键）分离，
// 因此 baseline 快照与 themeToCssVars(lightTheme) 的输出不受影响。
import { cssVarName, EXT } from './css-value.mjs'
import { isToken } from './resolver.mjs'

/** 输出顺序；与运行时 themeToCssVars 的 FOUNDATION_GROUPS 保持一致（测试校验）。 */
export const FOUNDATION_GROUPS = [
  'radius',
  'text',
  'space',
  'density',
  'elevation',
  'motion',
  'zIndex',
  'breakpoint',
  'brand',
]
const NON_FOUNDATION = new Set(['color', 'spacing', 'typography', 'light', 'dark'])

/**
 * 按声明顺序收集一个排列的 foundation 变量：`[{ path, value }]`。
 * 分组 `$extensions[EXT].keywords` 中的 CSS 关键字（如 tabular-nums）作为同组末尾的变量输出：
 * DTCG 没有关键字类型，写成 token 会违反规范。
 */
export function collectFoundation(raw, sdTree, isThemePath) {
  for (const key of Object.keys(sdTree)) {
    if (key.startsWith('$') || NON_FOUNDATION.has(key) || FOUNDATION_GROUPS.includes(key)) continue
    throw new Error(`unknown top-level token group "${key}": add it to FOUNDATION_GROUPS`)
  }
  const out = []
  const visit = (rawNode, sdNode, path) => {
    for (const [key, node] of Object.entries(sdNode)) {
      if (key.startsWith('$')) continue
      const p = [...path, key]
      if (isToken(node)) {
        if (!isThemePath(p)) out.push({ path: p, value: node.$value })
      } else visit(rawNode?.[key], node, p)
    }
    const keywords = rawNode?.$extensions?.[EXT]?.keywords
    for (const [key, value] of Object.entries(keywords ?? {}))
      out.push({ path: [...path, key], value })
  }
  for (const group of FOUNDATION_GROUPS) {
    if (!sdTree[group]) throw new Error(`missing foundation group "${group}"`)
    visit(raw[group], sdTree[group], [group])
  }
  return out
}

const keyOf = (path) => path.join('.')

/** 比较两种 mode 的取值，返回随 mode 变化的路径集合。 */
export function modeDependentPaths(light, dark) {
  const d = new Map(dark.map((e) => [keyOf(e.path), e.value]))
  return new Set(light.filter((e) => d.get(keyOf(e.path)) !== e.value).map((e) => keyOf(e.path)))
}

// ---------------------------------------------------------------------------
// CSS
// ---------------------------------------------------------------------------

const decl = (e) => `  ${cssVarName(e.path)}: ${String(e.value)};`

/** `:root` 放与 mode 无关的变量；随 mode 变化的放在 `[data-theme]` 块（与 KLineChart 根节点一致）。 */
export function emitFoundationCss(light, dark) {
  const varying = modeDependentPaths(light, dark)
  const shared = light.filter((e) => !varying.has(keyOf(e.path)))
  const block = (selector, entries) => `${selector} {\n${entries.map(decl).join('\n')}\n}`
  return [
    '/* Generated by `pnpm tokens:build`: design tokens v2 foundation. Do not edit. */',
    block(':root', shared),
    '',
    block(
      "[data-theme='light']",
      light.filter((e) => varying.has(keyOf(e.path))),
    ),
    '',
    block(
      "[data-theme='dark']",
      dark.filter((e) => varying.has(keyOf(e.path))),
    ),
    '',
  ].join('\n')
}

// ---------------------------------------------------------------------------
// TypeScript
// ---------------------------------------------------------------------------

function nest(entries) {
  const root = {}
  for (const { path, value } of entries) {
    let node = root
    for (const key of path.slice(0, -1)) node = node[key] ??= {}
    node[path.at(-1)] = value
  }
  return root
}

const tsKey = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) || /^\d+$/.test(k) ? k : `'${k}'`)
const tsValue = (v) =>
  typeof v === 'number' ? String(v) : v.includes("'") ? JSON.stringify(v) : `'${v}'`

function literal(node, indent) {
  const lines = []
  for (const [k, v] of Object.entries(node)) {
    if (v && typeof v === 'object') {
      lines.push(`${indent}${tsKey(k)}: {`, ...literal(v, `${indent}  `), `${indent}},`)
    } else lines.push(`${indent}${tsKey(k)}: ${tsValue(v)},`)
  }
  return lines
}

export function emitFoundationTs(light, dark, header) {
  const varying = modeDependentPaths(light, dark)
  const modeGroups = FOUNDATION_GROUPS.filter((g) =>
    [...varying].some((p) => p.split('.')[0] === g),
  )
  const sharedGroups = FOUNDATION_GROUPS.filter((g) => !modeGroups.includes(g))
  const pick = (entries, groups) => entries.filter((e) => groups.includes(e.path[0]))
  const omit = modeGroups.map((g) => `'${g}'`).join(' | ')
  const lines = [
    header,
    '// 设计 Token v2 基础层：圆角、字阶、间距、密度、阴影层级、动效、层级、断点与品牌强调色。',
    '// Theme 层（lightTheme / darkTheme）保持冻结；resolveTheme() 按 mode 挂载到 Theme.foundation。',
    "import type { FoundationTokens } from './types.js'",
    '',
    'const shared = {',
    ...literal(nest(pick(light, sharedGroups)), '  '),
    `} satisfies Omit<FoundationTokens, ${omit}>`,
    '',
  ]
  for (const [mode, entries] of [
    ['light', light],
    ['dark', dark],
  ]) {
    lines.push(`export const ${mode}Foundation: FoundationTokens = {`, '  ...shared,')
    lines.push(...literal(nest(pick(entries, modeGroups)), '  '), '}', '')
  }
  lines.push(
    '/** 按明暗模式索引的基础 Token。 */',
    "export const foundationTokens: Readonly<Record<'light' | 'dark', FoundationTokens>> = {",
    '  light: lightFoundation,',
    '  dark: darkFoundation,',
    '}',
    '',
  )
  return lines.join('\n')
}
