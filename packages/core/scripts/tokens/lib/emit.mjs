/** 把 resolver 中的文件 `$ref` 内联为源对象，得到单文件、可移植的 DTCG 解析器文档。 */
export function bundleResolver(doc, load) {
  const inlineSources = (sources) =>
    sources.map((s) => (s.$ref?.startsWith('#/') ? s : load(s.$ref)))
  const out = structuredClone(doc)
  out.description = `${doc.description} Bundled: file sources inlined by \`pnpm tokens:build\`.`
  for (const set of Object.values(out.sets ?? {})) set.sources = inlineSources(set.sources)
  for (const mod of Object.values(out.modifiers ?? {}))
    for (const [ctx, sources] of Object.entries(mod.contexts))
      mod.contexts[ctx] = inlineSources(sources)
  return out
}
